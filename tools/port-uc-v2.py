#!/usr/bin/env python3
"""Generate the Use Cases v2 layer of bolt-public-pages from the staging page
marketing/use-cases/ai-website-builder-v2/index.html.

The v2 page is the ai-website-builder mirror (production's rendered <main> + the
template's styles, already live as use-case-route.css) plus the v2 blocks. This
script ports ONLY the v2 blocks:

  CSS  <style id="uc2-hero-fan|uc2-hiw|uc2-built|uc2-pg|uc2-seams">
       → src/styles/use-case-v2.css, every rule scoped under the route wrapper's
         data-page="use-case" + data-v2 (pages not opted in are untouched);
         `:root[data-theme=…]` → `html[data-theme=…]`, keyframes `ucv2-`
         prefixed, `.sc-section-h2` → `.section-headline`, staging asset paths →
         /public-page-assets/use-cases/v2/.
  JS   <script id="uc2-hero-fan-js|uc2-hiw-js|uc2-built-js|uc2-pg-js">
       → public/public-page-assets/use-cases/use-case-v2.js. How it works loses
         its staging PRESETS table and review-only ?business= param: production
         renders the category's example as the section's JSON block.

The markup (fan cards, steps, prompt tabs, rail) is rendered by the route's
components from the CMS (src/components/use-case-v2/); the review-only
category switch and #uc2-types registry stay in staging.

    python3 tools/port-uc-v2.py ~/Projects/bpp-uc-v2
"""
import re, sys, pathlib, json

ROOT = pathlib.Path(__file__).resolve().parents[1]
repo = pathlib.Path(sys.argv[1]).expanduser()
src = (ROOT / 'marketing/use-cases/ai-website-builder-v2/index.html').read_text()

PFX = '.use-case-page.use-case-page[data-page="use-case"][data-v2]'
ASSET = '/public-page-assets/use-cases/v2/'

def block(tag, id_):
    m = re.search(rf'<{tag} id="{id_}">(.*?)</{tag}>', src, re.S)
    assert m, f'{tag}#{id_} not found'
    return m.group(1)

# ── CSS ─────────────────────────────────────────────────────────────────────
css = '\n'.join(block('style', i) for i in ('uc2-hero-fan', 'uc2-hiw', 'uc2-built', 'uc2-pg', 'uc2-seams'))
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
css = css.replace('../../../home/preview/hero/', ASSET + 'hero/')
assert '../' not in css, re.findall(r'url\([^)]*\.\./[^)]*\)', css)

def parse(s):
    items, i, n = [], 0, len(s)
    while i < n:
        j = s.find('{', i)
        if j == -1: break
        head = s[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if s[k] == '{': depth += 1
            elif s[k] == '}': depth -= 1
            k += 1
        items.append((head, s[j + 1:k - 1])); i = k
    return items

KF = set(re.findall(r'@keyframes\s+([\w-]+)', css))
def rename_kf(t):
    for k in sorted(KF, key=len, reverse=True):
        t = re.sub(r'(?<![\w-])' + re.escape(k) + r'(?![\w-])', 'ucv2-' + k, t)
    return t

HEAD = re.compile(r'^((?::root|html)(?:\[[^\]]*\]|:not\(\[[^\]]*\]\))*(?:\s+body)?)\s+(.*)$')
def scope(sel):
    sel = sel.strip().replace('.sc-section-h2', '.section-headline')
    m = HEAD.match(sel)
    head, rest = (m.group(1).replace(':root', 'html') + ' ', m.group(2)) if m else ('', sel)
    assert not rest.startswith(('html', ':root', 'body')), sel
    return f'{head}{PFX} {rest}'

def emit(items):
    out = []
    for head, body in items:
        h = head.strip()
        if not h: continue
        if h.startswith('@keyframes'):
            out.append(f'@keyframes ucv2-{h.split()[1]} {{{body}}}'); continue
        if h.startswith('@media') or h.startswith('@supports'):
            inner = emit(parse(body))
            if inner.strip(): out.append(f'{h} {{\n{inner}\n}}')
            continue
        assert not h.startswith('@'), h
        out.append(', '.join(scope(s) for s in h.split(',')) + ' {' + rename_kf(body) + '}')
    return '\n'.join(out)

generated = emit(parse(css))
header = '''/* ── /use-cases/<slug> — Use Cases v2 (hero video + template fan, the home
   page's five-scene How it works, prompt tabs over a scrollable result, Built
   with Bolt rail). GENERATED by tools/port-uc-v2.py in the sandbox repo
   (garyliusf/Enterprise) from marketing/use-cases/ai-website-builder-v2 — do
   not hand-edit; change the staging page and regenerate. Every rule is scoped
   under the route wrapper's data-v2, which [slug].astro sets only on pages
   opted into v2, so every other page is untouched. Loaded after
   use-case-route.css. ─────────────────────────────────────────────────── */
'''
(repo / 'src/styles/use-case-v2.css').write_text(header + generated + '\n')

# ── JS ──────────────────────────────────────────────────────────────────────
fan = block('script', 'uc2-hero-fan-js')
built = block('script', 'uc2-built-js')
pg = block('script', 'uc2-pg-js')
hiw = block('script', 'uc2-hiw-js')
# the staging presets table + ?business= → the section's own JSON block (rendered from the CMS)
a = hiw.index('  var PRESETS = ')
b = hiw.index('  var C = B.colors')
hiw = hiw[:a] + '''  var B = {};
  var data = section.querySelector('.uc2-hiw-business');
  if (data) { try { B = JSON.parse(data.textContent) || {}; } catch (e) {} }
''' + hiw[b:]
hiw = re.sub(r"/\* the businesses the story can build.*?\*/\n", '', hiw, flags=re.S)
assert "var HOME = '../../../home/preview/';" in hiw
hiw = hiw.replace("var HOME = '../../../home/preview/';", f"var HOME = '{ASSET}';")
assert 'PRESETS' not in hiw and '../' not in hiw
for name, js in (('fan', fan), ('built', built), ('pg', pg)):
    assert '../' not in js, name

js = '''/* /use-cases/<slug> — Use Cases v2 behaviour. GENERATED by tools/port-uc-v2.py
   in the sandbox repo from marketing/use-cases/ai-website-builder-v2 — do not
   hand-edit. Loaded only on pages the route opts into v2 (data-v2). The prompt
   boxes are wired to bolt.new by use-case-page.js (.re-prompt-shell). */
(function () {
if (!document.querySelector('.use-case-page[data-v2]')) return;
''' + fan + '\n' + hiw + '\n' + built + '\n' + pg + '\n})();\n'
(repo / 'public/public-page-assets/use-cases/use-case-v2.js').write_text(js)
print(f'css: {len(generated.splitlines())} lines, keyframes {len(KF)}; js: {len(js):,} bytes')
